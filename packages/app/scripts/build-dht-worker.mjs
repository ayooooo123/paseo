// Packs the Bare worker (src/runtime/dht/dht-worker.mjs) into a self-contained
// bundle via `bare-pack`, then regenerates a lazy CommonJS source module. Keeping
// the large payload outside the TypeScript module avoids parsing and decoding a
// base64 literal during app startup.
//
// Run during native builds (prebuild / EAS post-install). Requires the Bare
// toolchain + native prebuilds for the target ABIs; produces a linked bundle.
import { spawnSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const appRoot = resolve(here, "..");
const entry = join(appRoot, "src/runtime/dht/dht-worker.mjs");
const resolverFile = join(appRoot, "src/runtime/dht/dht-worker-bundle.ts");
const sourceFile = join(appRoot, "src/runtime/dht/dht-worker.bundle.js");
const outDir = mkdtempSync(join(tmpdir(), "paseo-dht-worker-"));
const outBundle = join(outDir, "dht-worker.bundle");

// bare-pack bundles per host triple (`--host`), resolving `linked:` addons for
// each target ABI. Cover iOS device + simulator and the common Android ABIs.
const hosts = ["ios-arm64", "ios-arm64-simulator", "android-arm64", "android-arm", "android-x64"];
const args = [
  "bare-pack",
  ...hosts.flatMap((host) => ["--host", host]),
  "--linked",
  "--out",
  outBundle,
  entry,
];
const result = spawnSync("npx", args, { cwd: appRoot, stdio: "inherit" });
if (result.status !== 0) {
  throw new Error(`bare-pack failed (exit ${result.status ?? "signal"})`);
}

const source = readFileSync(outBundle, "utf8");
writeFileSync(
  sourceFile,
  `// GENERATED by scripts/build-dht-worker.mjs — do not edit by hand.\nmodule.exports = ${JSON.stringify(source)};\n`,
);
const generated = `// GENERATED by scripts/build-dht-worker.mjs — do not edit by hand.
declare const require: (moduleName: string) => unknown;

let cachedSource: string | null | undefined;

export function resolveDhtWorkerBundle(): string | null {
  if (cachedSource !== undefined) return cachedSource;
  const loaded = require("./dht-worker.bundle.js");
  cachedSource = typeof loaded === "string" ? loaded : null;
  return cachedSource;
}
`;
writeFileSync(resolverFile, generated);
console.log(`Wrote ${sourceFile} and ${resolverFile} (${source.length} source chars)`);
